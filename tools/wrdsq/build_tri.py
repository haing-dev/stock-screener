"""Build tools/wrdsq/lib/tri_wrds.py: the live triage rules, events, cells, calls and statistics (copied unchanged
from triage/*.py and qs/btstats.py) plus the WRDS adapter (tools/wrdsq/tri_wrds_adapter.py), as ONE module that runs
on WRDS Cloud through wrdsq (python steps: `import tri_wrds; tri_wrds.pull(sql, save, out)` / `tri_wrds.run(load,
save, out)`). Re-run after any change to the triage rules so the WRDS backtest uses the same code.

    python3 tools/wrdsq/build_tri.py
"""
import ast
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "tools", "wrdsq", "lib", "tri_wrds.py")
DROP = re.compile(r"^(from \.|from qs\.|import os$|from \. import)")


def body(path, rename=None):
    src = open(os.path.join(ROOT, path), encoding="utf-8").read()
    tree = ast.parse(src)
    lines = src.split("\n")
    # drop the module docstring and the package-relative / qs imports (multi-line imports included)
    skip = set()
    for node in tree.body:
        if isinstance(node, ast.Expr) and isinstance(getattr(node, "value", None), ast.Constant) \
                and isinstance(node.value.value, str) and node is tree.body[0]:
            skip.update(range(node.lineno - 1, node.end_lineno))
        if isinstance(node, ast.ImportFrom) and (node.level > 0 or (node.module or "").startswith("qs")):
            skip.update(range(node.lineno - 1, node.end_lineno))
    out = "\n".join(ln for i, ln in enumerate(lines) if i not in skip)
    for old, new in (rename or {}).items():
        out = re.sub(r"(?<![.\w])%s(?!\w)" % old, new, out)
    return "# " + "-" * 80 + " from " + path + "\n" + out.strip() + "\n"


def pick(path, names):
    """Top-level assignments / functions with these names, in file order."""
    src = open(os.path.join(ROOT, path), encoding="utf-8").read()
    tree = ast.parse(src)
    lines = src.split("\n")
    parts = []
    for node in tree.body:
        nm = node.name if isinstance(node, (ast.FunctionDef, ast.ClassDef)) else \
            (node.targets[0].id if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) else None)
        if nm in names:
            parts.append("\n".join(lines[node.lineno - 1:node.end_lineno]))
    return "# " + "-" * 80 + " from " + path + " (" + ", ".join(names) + ")\n" + "\n\n\n".join(parts) + "\n"


def constants():
    import sys
    sys.path.insert(0, ROOT)
    from qs.industry import EMERGING_EXTRA_EXCLUDE, NEVER
    from qs.screens import STRUCTURAL_EXCLUDE, STRUCTURAL_KEEP
    cfg = json.load(open(os.path.join(ROOT, "config.json"), encoding="utf-8"))
    h = cfg["portal"]["holders"]
    rng = lambda lst: [(a, b) for a, b, *_ in lst]  # noqa: E731
    vals = {
        "NEVER_SIC": rng(NEVER), "STRUCT_EXCL": rng(STRUCTURAL_EXCLUDE), "STRUCT_KEEP": rng(STRUCTURAL_KEEP),
        "EMERGING_EXTRA": rng(EMERGING_EXTRA_EXCLUDE),
        "CORE_EXCL": [(x["from"], x["to"]) for x in cfg["exclude_sic"]],
        "SCREEN_ANYWAY": sorted(cfg.get("screen_anyway") or {}),
        "HOLDERS_PASSIVE": list(h.get("passive") or []), "HOLDERS_EXCLUDE": list(h.get("exclude") or []),
        "HOLDERS_MAX_POS": int(h.get("max_positions", 1000)), "HOLDERS_HUGE_AUM": float(h.get("huge_aum", 250e9)),
        "HOLDERS_HUGE_POS": int(h.get("huge_aum_positions", 500)),
    }
    return "# " + "-" * 80 + " constants from config.json, qs/industry.py, qs/screens.py\n" + \
        "\n".join(f"{k} = {v!r}" for k, v in vals.items()) + "\n"


PRELUDE = '''"""tri_wrds - the Quality Triage (triage/ v{ver}) backtested on WRDS data. GENERATED by tools/wrdsq/build_tri.py:
do not edit; change triage/*.py or tools/wrdsq/tri_wrds_adapter.py and rebuild.

  pull(sql, save, out)   CRSP / Compustat / CCM / 13F / Fama-French pulls into ~/wrdsq/data (tri_*)
  run(load, save, out)   panel -> events -> cells -> calls -> outcomes -> statistics (printed); saves tri_events
"""
import sys

R = SC = sys.modules[__name__]


class P:                                   # paths stub: the copied code writes nothing on WRDS
    OUT = RETURNS = "."

    @staticmethod
    def ensure(*_a):
        return None


class PN:                                  # panel stub: detect() is given load= explicitly
    @staticmethod
    def load(_ym):
        return None

'''


def build():
    ver = re.search(r'__version__\s*=\s*"([^"]+)"', open(os.path.join(ROOT, "triage", "__init__.py")).read()).group(1)
    parts = [PRELUDE.replace("{ver}", ver), constants(),
             pick("qs/btstats.py", ["FACTORS", "nw_lags", "ols_nw"]),
             body("triage/rules.py"),
             body("triage/episodes.py", {"KINDS": "KIND_IDS"}),
             body("triage/score.py"),
             body("triage/stats.py", {"CAP": "CAP_PCT"}),
             pick("triage/build.py", ["_event_learning"]),
             open(os.path.join(ROOT, "tools", "wrdsq", "tri_wrds_adapter.py"), encoding="utf-8").read()]
    src = "\n\n".join(parts)
    # episodes' KINDS rename must not touch R.KINDS; check top-level names are defined once
    tree = ast.parse(src)
    seen = {}
    for node in tree.body:
        nms = [node.name] if isinstance(node, (ast.FunctionDef, ast.ClassDef)) else \
            [t.id for t in getattr(node, "targets", []) if isinstance(t, ast.Name)]
        for nm in nms:
            seen.setdefault(nm, []).append(node.lineno)
    allowed = {"write", "PN", "P", "R", "SC", "_cagr", "_median_nm", "is_match"}
    dup = {k: v for k, v in seen.items() if len(v) > 1 and k not in allowed}
    assert not dup, f"names defined twice: {dup}"
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(src)
    compile(src, OUT, "exec")
    print(f"wrote {OUT} ({len(src)} bytes, triage v{ver})")


if __name__ == "__main__":
    build()
