PERIODS = (("1975-01", "1989-12"), ("1990-01", "2010-12"))


def _cols(sql, table):
    return list(sql("select * from %s limit 1" % table).columns)


def _score(fc, real, ret_m):
    """fc, real: annualised vols aligned so fc[t] forecasts real[t+1]; ret_m: monthly return of t+1."""
    j = pd.concat([fc, real, ret_m], axis=1, keys=["f", "r", "x"]).dropna()
    j = j[(j.f > 0) & (j.r > 0)]
    if len(j) < 24:
        return None
    lf, lr = np.log(j.f), np.log(j.r)
    r2 = np.corrcoef(lf, lr)[0, 1] ** 2
    qlike = float(np.mean((j.r / j.f) ** 2 - np.log((j.r / j.f) ** 2) - 1))
    scaled = (j.x / (j.f / np.sqrt(12))).std()
    return {"n": len(j), "bias": float(np.mean(lr - lf)), "r2": float(r2), "qlike": qlike, "scaled_sd": float(scaled)}


def msci_names(sql):
    n = sql("select gvkeyx, conm from comp.g_idx_index where position('MSCI' in conm) > 0")
    n["conm"] = n["conm"].astype(str).str.strip()
    n = n[n["conm"].str.contains(r"^MSCI\s*-\s*[A-Za-z .]+ Index", regex=True)]
    n = n[~n["conm"].str.contains("Islamic|Small|Value|Growth|Sector| ex | Ex |Free|World|Europe|Pacific|EAFE|Emerging|"
                                  "Far East|Nordic|Kokusai|EMU|AC |Latin|Asia|North America|G7", regex=True)]
    return n


def run_vol(sql, out):
    names = msci_names(sql)
    out("MSCI country indexes found:", len(names), "| e.g.", list(names["conm"].head(3)))
    keys = ",".join("'%s'" % g for g in names["gvkeyx"])
    d = sql("select gvkeyx, datadate, prccd from comp.g_idx_daily where gvkeyx in (%s) and datadate >= '1972-01-01' "
            "and datadate <= '2010-12-31' and prccd > 0" % keys)
    d["datadate"] = pd.to_datetime(d["datadate"])
    series = {}
    for g, x in d.groupby("gvkeyx"):
        s = x.set_index("datadate")["prccd"].sort_index()
        s = s[~s.index.duplicated()]
        series[names.set_index("gvkeyx").loc[g, "conm"].replace("MSCI - ", "").split(" Index")[0]] = np.log(s).diff()
    try:
        u = sql("select date, vwretx from crsp.dsi where date >= '1972-01-01' and date <= '2010-12-31'")
        u["date"] = pd.to_datetime(u["date"])
        series["USA (CRSP)"] = np.log1p(u.set_index("date")["vwretx"].astype(float))
    except Exception as e:  # noqa: BLE001
        out("crsp.dsi not used:", str(e)[:120])
    res = {k: {p: [] for p in PERIODS} for k in "abcd"}
    for name, r in series.items():
        r = r.dropna()
        r = r[r.abs() < 0.25]                         # drop data errors (|daily log move| >= 25%)
        if len(r) < 2500:
            continue
        m = r.groupby(r.index.to_period("M"))
        real = m.std() * np.sqrt(252)
        mret = m.sum()
        a = mret.rolling(36, min_periods=24).std() * np.sqrt(12)
        ew = (r ** 2).ewm(halflife=35).mean().groupby(r.index.to_period("M")).last() ** 0.5 * np.sqrt(252)
        lt = (r ** 2).rolling(2520, min_periods=750).mean().groupby(r.index.to_period("M")).last() ** 0.5 * np.sqrt(252)
        c = (0.7 * ew + 0.3 * lt).fillna(ew)
        floor = 0.75 * real.rolling(120, min_periods=36).median()
        dd = np.maximum(c, floor.fillna(0))
        for key, fc in (("a", a), ("b", ew), ("c", c), ("d", dd)):
            f1 = fc.shift(1)                          # forecast made at end of t-1 for month t
            for p in PERIODS:
                sl = slice(pd.Period(p[0], "M"), pd.Period(p[1], "M"))
                sc = _score(f1.loc[sl], real.loc[sl], mret.loc[sl])
                if sc:
                    res[key][p].append(sc)
    labels = {"a": "36m monthly std (current)", "b": "EWMA daily, 35d half-life", "c": "0.7 EWMA + 0.3 10y",
              "d": "(c) with floor 0.75 x 10y median"}
    for p in PERIODS:
        out("== %s..%s (markets averaged)" % (p[0][:4], p[1][:4]))
        for k in "abcd":
            L = res[k][p]
            if not L:
                continue
            avg = {f: np.mean([x[f] for x in L]) for f in ("bias", "r2", "qlike", "scaled_sd")}
            out("  %-34s markets %2d | R2 %.2f | QLIKE %.3f | bias %+.2f | sd of vol-scaled returns %.2f" % (
                labels[k], len(L), avg["r2"], avg["qlike"], avg["bias"], avg["scaled_sd"]))


